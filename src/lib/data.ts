// ── Helper ──
export function getAllResources(): Resource[] {
  return [
    ...reports,
    ...datasets,
    ...publications,
    ...photographs,
    ...videos,
    ...audioRecordings,
  ];
}

export function getResourceById(id: string): Resource | undefined {
  return getAllResources().find(r => r.id === id);
}

export function getExpeditionById(id: string): Expedition | undefined {
  return expeditions.find(e => e.id === id);
}

export function getRelatedResources(expeditionId: string): Resource[] {
  return getAllResources().filter(r => r.expeditionId === expeditionId);
}

export function searchResources(query: string): Resource[] {
  const q = query.toLowerCase();
  return getAllResources().filter(r =>
    r.title.toLowerCase().includes(q) ||
    r.description.toLowerCase().includes(q) ||
    r.keywords.some(k => k.toLowerCase().includes(q)) ||
    r.researchArea.toLowerCase().includes(q)
  );
}
